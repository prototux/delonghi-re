#define PORTDbits PIC_BITS(PORTD, RD0:1, RD1:1, RD2:1, RD3:1, RD4:1, RD5:1, RD6:1, RD7:1)
#define PORTEbits PIC_BITS(PORTE, RE0:1, RE1:1, RE2:1, RE3:1, :4)
