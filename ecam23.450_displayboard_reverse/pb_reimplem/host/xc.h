#define RCSTAbits PIC_BITS(RCSTA, RX9D:1, OERR:1, FERR:1, ADDEN:1, CREN:1, SREN:1, RX9:1, SPEN:1)
#define TXSTAbits PIC_BITS(TXSTA, TX9D:1, TRMT:1, BRGH:1, SENDB:1, SYNC:1, TXEN:1, TX9:1, CSRC:1)
#define ADCON0bits PIC_BITS(ADCON0, ADON:1, GO:1, CHS0:1, CHS1:1, CHS2:1, CHS3:1, :2)
#define EECON1bits PIC_BITS(EECON1, RD:1, WR:1, WREN:1, WRERR:1, FREE:1, :1, CFGS:1, EEPGD:1)
#define WDTCONbits PIC_BITS(WDTCON, SWDTEN:1, :7)
#endif
