function fromColumns(cols) {
  const rows = new Array(8).fill(0);
  for (let x = 0; x < 5; x++) for (let y = 0; y < 8; y++) if (cols[x] & (1 << y)) rows[y] |= 1 << (4 - x);
  return rows;
}

function rasterise(ch) {
  if (typeof document === 'undefined') return null;
  const c = document.createElement('canvas');
  c.width = 50; c.height = 80;
  const g = c.getContext('2d');
  g.fillStyle = '#000'; g.fillRect(0, 0, 50, 80);
  g.fillStyle = '#fff'; g.font = 'bold 74px sans-serif'; g.textAlign = 'center'; g.textBaseline = 'alphabetic';
  g.fillText(ch, 25, 68);
  const d = g.getImageData(0, 0, 50, 80).data;
  const rows = new Array(8).fill(0);
  for (let y = 0; y < 8; y++) for (let x = 0; x < 5; x++) {
    let s = 0;
    for (let yy = 0; yy < 10; yy++) for (let xx = 0; xx < 10; xx++) s += d[((y * 10 + yy) * 50 + x * 10 + xx) * 4];
    if (s / 100 > 90) rows[y] |= 1 << (4 - x);
  }
  return rows;
}

const cache = new Map();

// 8 rows of 5 bits for a ROM code (CGRAM codes are handled by the caller)
export function glyph(code) {
  if (cache.has(code)) return cache.get(code);
  let rows;
  if (code >= 0x20 && code <= 0x7e) rows = fromColumns(ASCII[code - 0x20]);
  else if (code === 0xff) rows = [31, 31, 31, 31, 31, 31, 31, 31];
  else if (HIGH[code]) {
    const ch = HIGH[code];
    const [base, mark] = ch.normalize('NFD');
    if (mark && ACCENT[mark] && base.charCodeAt(0) < 0x7f) {
      const b = fromColumns(ASCII[base.charCodeAt(0) - 0x20]);
      if (base >= 'A' && base <= 'Z') {
        rows = [ACCENT[mark][0], ...b.slice(0, 7)];        // capital moved down one row
      } else {
        rows = b.slice();
        rows[0] |= ACCENT[mark][0];
        rows[1] |= ACCENT[mark][1];
      }
    } else {
      rows = rasterise(ch);
    }
  }
  if (!rows) rows = [0b10101, 0, 0b10001, 0, 0b10001, 0, 0b10101, 0];   // unknown code
  cache.set(code, rows);
  return rows;
}
